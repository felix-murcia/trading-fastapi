"""Puertos de dominio (Protocol, no ABC). Solo firmas, sin infraestructura."""

from typing import Protocol


class TradeRepository(Protocol):
    def save(self, trade) -> None: ...
    def find_by_id(self, id: str): ...
    def save_outcome(self, outcome) -> None: ...
    def load_outcomes(self, symbol: str) -> list: ...
    def save_state(self, symbol: str, state: object) -> None: ...
    def load_state(self, symbol: str) -> object | None: ...


class AuditLogger(Protocol):
    def log(self, event: str, details: dict) -> None: ...


class LLMClient(Protocol):
    def veto(self, signal: dict) -> bool: ...
    def classify_regime(self, data: dict) -> str: ...
    def query(self, symbol: str, decision: str, ml_prob: float, context: dict) -> dict: ...


class BrokerGateway(Protocol):
    def execute(self, order: dict) -> dict: ...
    def get_price(self, symbol: str) -> float: ...


class Clock(Protocol):
    def now(self) -> object: ...


class ConfigProvider(Protocol):
    def get(self, key: str, default=None): ...


class Severity:
    INFO = "info"
    WARNING = "warning"
    ERROR = "error"


class ModelTrainer(Protocol):
    """Entrena un modelo de ML. Infraestructura: PPO, gymnasium, etc. (8d)."""

    def train(self, dataset: object, config: object) -> object: ...
    def evaluate(self, model: object, dataset: object) -> dict: ...


class ModelRepository(Protocol):
    """Persiste/carga modelos y manifiestos. Infraestructura: filesystem, model_registry (8d)."""

    def save_model(self, model: object, metadata: dict) -> str: ...
    def load_latest(self, symbol: str) -> object | None: ...
    def promote(self, model_id: str) -> None: ...
    def get_manifest(self, model_path: str) -> dict: ...


class DataFetcher(Protocol):
    """Obtiene datos de entrenamiento. Infraestructura: DB, MT5 MCP, etc. (8d)."""

    def fetch_trade_outcomes(self, symbol: str, since: float | None = None) -> list: ...
    def fetch_candles(self, symbol: str, count: int, timeframe: str = "H1") -> list: ...


class Notifier(Protocol):
    """Envía alertas. Infraestructura: Telegram, Slack, email, etc. (8d)."""

    def notify(self, message: str, severity: str = Severity.INFO) -> None: ...
